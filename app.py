"""AI Job Finder — Streamlit entry point.

Sets up the page and session, then shows the selected page from views/.
Sources, matching and tracker logic live in app_core.py.
"""
from app_core import *  # noqa: F401,F403
from app_core import _secret
from views import dashboard, find_jobs, job_tracker, my_resume

st.set_page_config(page_title='AI Job Finder', layout='wide', initial_sidebar_state='auto')

st.markdown(APP_CSS, unsafe_allow_html=True)

for key, default in {'jobs': [], 'resume_text': '',
                     'confirmed_qualifications': [], 'seen_jobs': [],
                     'search_baseline': False, 'tracker_unlocked': False,
                     'profile_answers': dict(LEGACY_DEFAULT_ANSWERS),
                     'save_resume_with_tracker': False,
                     'saved_searches': [],
                     'tracker_loaded': False}.items():
    if key not in st.session_state:
        st.session_state[key] = default

# Streamlit can retain session results through hot reloads. Never present
# rankings generated by older scoring code as though they came from this build.
if needs_search_refresh(st.session_state.get('matching_engine_version')):
    had_previous_results = 'search_results' in st.session_state
    st.session_state.pop('search_results', None)
    st.session_state.pop('search_stats', None)
    st.session_state.pop('search_page', None)
    st.session_state.matching_engine_version = MATCHING_ENGINE_VERSION
    st.session_state.matching_engine_reset = had_previous_results

if JOB_SOURCE_CATALOG_ERROR:
    st.error('Job source configuration needs attention: ' + JOB_SOURCE_CATALOG_ERROR)
    st.stop()

consume_search_update()

# Sidebar navigation, laid out like the MDN billing app: wordmark, then one
# row per page. The widget key stays 'top_navigation' so saved sessions,
# tests and the search-progress refresh keep working. On phones Streamlit
# collapses the sidebar behind its menu button.
with st.sidebar:
    st.markdown(brand(MATCHING_ENGINE_VERSION),unsafe_allow_html=True)
    page = st.radio(
        'Navigation',
        ['Dashboard','Find Jobs','Job Tracker','My Resume'],
        label_visibility='collapsed',key='top_navigation'
    )
    st.divider()
    _tracked=len(st.session_state.jobs)
    st.caption(f"{_tracked} job{'s' if _tracked!=1 else ''} in your tracker")

sync_notice=st.empty()

render_search_progress()

if page == 'Dashboard':
    dashboard.render()
elif page == 'My Resume':
    my_resume.render()
elif page == 'Find Jobs':
    find_jobs.render()
elif page == 'Job Tracker':
    job_tracker.render()

with sync_notice.container():
    tracker_sync.render_sync_status(_secret('TRACKER_DATABASE_URL'),
        _secret('TRACKER_WORKSPACE_ID') or 'personal',tracker_cloud_enabled())
